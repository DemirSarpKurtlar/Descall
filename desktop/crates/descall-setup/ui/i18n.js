  /* Turkish locative suffix for a number ("%62'de", "%40'ta"): follows the spoken last word. */
  function trLocative(n) {
    n = Math.abs(Math.round(n));
    if (n === 0) return "da";
    const ones = n % 10, tens = Math.floor(n / 10) % 10;
    const byOnes = { 1: "de", 2: "de", 3: "te", 4: "te", 5: "te", 6: "da", 7: "de", 8: "de", 9: "da" };
    const byTens = { 1: "da", 2: "de", 3: "da", 4: "ta", 5: "de", 6: "ta", 7: "te", 8: "de", 9: "da" };
    if (ones) return byOnes[ones];
    if (tens) return byTens[tens];
    if (n % 1000 === 0) return n % 1000000 === 0 ? "da" : "de"; /* bin -> de, milyon -> da */
    return "de"; /* yüz */
  }

  function pick(tag) {
    const t = String(tag || "").toLowerCase();
    if (t.startsWith("pt")) return "pt-BR";
    for (const [code] of LANGS) if (t === code.toLowerCase() || t.split(/[-_]/)[0] === code) return code;
    return "en";
  }

