//! `descall-shell://` pages: the notification capsule and the voice overlay.
//!
//! The markup is not re-implemented. These pages run the Electron renderer modules
//! themselves (frontend/electron/notificationCard.cjs, overlayHtml.cjs and mainI18n.cjs with
//! its catalogs) through a tiny CommonJS shim, so both desktop shells draw the same pixels
//! and an Electron change is picked up by the next Tauri build. On Windows the scheme is
//! served as https://descall-shell.localhost, a local origin for Tauri's IPC.

use std::sync::OnceLock;

const NOTIFICATION_CARD: &str = include_str!("../../../../frontend/electron/notificationCard.cjs");
const OVERLAY_HTML: &str = include_str!("../../../../frontend/electron/overlayHtml.cjs");
const MAIN_I18N: &str = include_str!("../../../../frontend/electron/mainI18n.cjs");
const APP_ICON: &[u8] = include_bytes!("../../../../frontend/electron/descall-icon.png");
pub const NOTIF_JS: &str = include_str!("../../../app/shim/shell-notif.js");
pub const OVERLAY_JS: &str = include_str!("../../../app/shim/shell-overlay.js");

/// Response CSP of every shell page. `unsafe-inline` covers the capsule's own inline motion
/// script and the overlay's script (both generated by the Electron modules); nothing remote
/// is ever loaded as script here.
pub const CSP: &str = "default-src 'none'; script-src 'self' 'unsafe-inline'; style-src 'unsafe-inline'; img-src https: data:; font-src data:; connect-src ipc: http://ipc.localhost";

fn js_string(s: &str) -> String {
    serde_json::to_string(s).unwrap_or_else(|_| "\"\"".into())
}

fn base64(bytes: &[u8]) -> String {
    const T: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = String::with_capacity(bytes.len().div_ceil(3) * 4);
    for c in bytes.chunks(3) {
        let n = (c[0] as u32) << 16 | (*c.get(1).unwrap_or(&0) as u32) << 8 | *c.get(2).unwrap_or(&0) as u32;
        out.push(T[(n >> 18) as usize & 63] as char);
        out.push(T[(n >> 12) as usize & 63] as char);
        out.push(if c.len() > 1 { T[(n >> 6) as usize & 63] as char } else { '=' });
        out.push(if c.len() > 2 { T[n as usize & 63] as char } else { '=' });
    }
    out
}

/// CommonJS modules + the files they read, plus `__descallMountShellPage(html)`.
pub fn runtime_js() -> &'static str {
    static JS: OnceLock<String> = OnceLock::new();
    JS.get_or_init(|| {
        let mut files = String::from("{");
        files.push_str(&format!("{}:{},", js_string("/src/i18n/locales.json"), js_string(crate::i18n::REGISTRY_JSON)));
        for (id, text) in crate::i18n::CATALOGS {
            files.push_str(&format!("{}:{},", js_string(&format!("/electron/i18n/{id}.json")), js_string(text)));
        }
        files.push('}');
        format!(
            r#"(function (root) {{
  "use strict";
  var FILES = {files};
  var ICON_B64 = {icon};
  function norm(p) {{
    var out = [];
    String(p).split("/").forEach(function (s) {{ if (!s || s === ".") return; if (s === "..") out.pop(); else out.push(s); }});
    return "/" + out.join("/");
  }}
  var path = {{
    join: function () {{ return norm(Array.prototype.slice.call(arguments).join("/")); }},
    dirname: function (p) {{ var n = norm(p); return n.slice(0, n.lastIndexOf("/")) || "/"; }},
    basename: function (p) {{ var n = norm(p); return n.slice(n.lastIndexOf("/") + 1); }},
    extname: function (p) {{ var b = path.basename(p); var i = b.lastIndexOf("."); return i > 0 ? b.slice(i) : ""; }},
  }};
  var fs = {{
    readFileSync: function (p) {{
      var n = norm(p);
      if (n === "/electron/descall-icon.png") return {{ toString: function () {{ return ICON_B64; }} }};
      if (Object.prototype.hasOwnProperty.call(FILES, n)) return FILES[n];
      var e = new Error("ENOENT: " + n); e.code = "ENOENT"; throw e;
    }},
    writeFileSync: function () {{}},
  }};
  // notificationCard.cjs crc32 uses Buffer.from(text, "utf8"); bytes are all it needs.
  var Buffer = {{ from: function (s) {{ return new TextEncoder().encode(String(s)); }} }};
  var SOURCES = {{}};
  var CACHE = {{}};
  function req(name) {{
    if (name === "fs") return fs;
    if (name === "path") return path;
    var key = String(name).replace(/^\.\//, "");
    if (CACHE[key]) return CACHE[key].exports;
    var fn = SOURCES[key];
    if (!fn) throw new Error("module not bundled: " + name);
    var module = {{ exports: {{}} }};
    CACHE[key] = module;
    fn(module, module.exports, req, "/electron", "/electron/" + key);
    return module.exports;
  }}
  SOURCES["mainI18n.cjs"] = function (module, exports, require, __dirname, __filename) {{
{main_i18n}
  }};
  SOURCES["notificationCard.cjs"] = function (module, exports, require, __dirname, __filename) {{
{card}
  }};
  SOURCES["overlayHtml.cjs"] = function (module, exports, require, __dirname, __filename) {{
{overlay}
  }};
  root.__descallShellRequire = req;
  // Swap this page for a full HTML document built by an Electron module: styles into
  // <head>, markup into <body>, then the document's own scripts, in order.
  root.__descallMountShellPage = function (html) {{
    var doc = new DOMParser().parseFromString(String(html), "text/html");
    var d = root.document;
    d.documentElement.lang = doc.documentElement.lang || "en";
    doc.head.querySelectorAll("style").forEach(function (s) {{ d.head.appendChild(d.importNode(s, true)); }});
    d.body.className = doc.body.className;
    var scripts = [];
    doc.body.querySelectorAll("script").forEach(function (s) {{ scripts.push(s.textContent); s.remove(); }});
    d.body.innerHTML = doc.body.innerHTML;
    scripts.forEach(function (code) {{ var el = d.createElement("script"); el.textContent = code; d.body.appendChild(el); }});
  }};
}})(typeof window !== "undefined" ? window : globalThis);
"#,
            files = files,
            icon = js_string(&base64(APP_ICON)),
            main_i18n = MAIN_I18N,
            card = NOTIFICATION_CARD,
            overlay = OVERLAY_HTML,
        )
    })
}

fn page(script: &str) -> String {
    format!(
        "<!DOCTYPE html><html><head><meta charset=\"utf-8\"><style>html,body{{margin:0;background:transparent;overflow:hidden}}</style>\
<script src=\"/runtime.js\"></script></head><body><script src=\"/{script}\"></script></body></html>"
    )
}

/// (content type, body) for a path of the scheme, or None (404).
pub fn serve(path: &str) -> Option<(&'static str, Vec<u8>)> {
    let html = "text/html; charset=utf-8";
    let js = "text/javascript; charset=utf-8";
    Some(match path {
        "/notif.html" => (html, page("notif.js").into_bytes()),
        "/overlay.html" => (html, page("overlay.js").into_bytes()),
        "/runtime.js" => (js, runtime_js().as_bytes().to_vec()),
        "/notif.js" => (js, NOTIF_JS.as_bytes().to_vec()),
        "/overlay.js" => (js, OVERLAY_JS.as_bytes().to_vec()),
        _ => return None,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn serves_known_paths_only() {
        assert!(serve("/notif.html").unwrap().1.starts_with(b"<!DOCTYPE html>"));
        assert!(serve("/runtime.js").is_some());
        assert!(serve("/../Cargo.toml").is_none());
        assert!(serve("/notif.html?x").is_none(), "the handler strips the query first");
        assert_eq!(base64(b"Man"), "TWFu");
        assert_eq!(base64(b"Ma"), "TWE=");
        assert_eq!(base64(b"M"), "TQ==");
    }

    /// The bundled Electron modules load and render through the shim (needs `node`, which
    /// CI and dev machines have; skipped when it is missing).
    #[test]
    fn electron_modules_render_through_the_runtime() {
        let Ok(out) = std::process::Command::new("node").arg("--version").output() else { return };
        if !out.status.success() {
            return;
        }
        let dir = std::env::temp_dir().join(format!("descall-shell-pages-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(dir.join("runtime.js"), runtime_js()).unwrap();
        let check = r#"
const vm = require("vm");
const fs = require("fs");
const ctx = { console, TextEncoder };
ctx.globalThis = ctx;
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(process.argv[2], "utf8"), ctx);
const req = ctx.__descallShellRequire;
const i18n = req("./mainI18n.cjs");
i18n.setLocale("tr");
const card = req("./notificationCard.cjs");
const m = card.describeNotification({ title: "Ayşe", body: "selam", data: { type: "dm", from: "Ayşe" } });
if (m.kind !== "message" || m.context !== i18n.et("notif.now")) throw new Error("describe " + JSON.stringify(m));
const html = card.buildNotificationHtml({ title: m.name, body: m.preview, model: m, duration: 5000 });
if (!html.includes("Ayşe") || !html.includes("<script>") || !html.startsWith("<!DOCTYPE html>")) throw new Error("card html");
const app = card.describeNotification({ title: "Descall", body: "x", appIcon: true });
if (!card.buildNotificationHtml({ title: "Descall", body: "x", model: app }).includes("data:image/png;base64,iVBOR")) throw new Error("app icon");
const ov = req("./overlayHtml.cjs");
const o = ov.buildOverlayHtml({ lang: "de" });
if (!o.includes("muteBtn") || ov.STRINGS.de.end !== "Anruf beenden") throw new Error("overlay");
console.log("ok");
"#;
        std::fs::write(dir.join("check.js"), check).unwrap();
        let out = std::process::Command::new("node").arg(dir.join("check.js")).arg(dir.join("runtime.js")).output().unwrap();
        let _ = std::fs::remove_dir_all(&dir);
        assert!(out.status.success(), "{}{}", String::from_utf8_lossy(&out.stdout), String::from_utf8_lossy(&out.stderr));
    }
}
