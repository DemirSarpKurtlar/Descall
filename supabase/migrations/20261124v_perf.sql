CREATE INDEX IF NOT EXISTS perf_rollup_hourly_bucket_idx ON public.perf_rollup_hourly (bucket DESC);

CREATE TABLE IF NOT EXISTS public.perf_rollup_daily (
  day date NOT NULL,
  metric text NOT NULL,
  route text NOT NULL DEFAULT '',
  platform text NOT NULL,
  app_version text NOT NULL DEFAULT '',
  device_class text NOT NULL DEFAULT '',
  connection text NOT NULL DEFAULT '',
  country text NOT NULL DEFAULT '',
  n integer NOT NULL DEFAULT 0 CHECK (n >= 0),
  good integer NOT NULL DEFAULT 0 CHECK (good >= 0),
  ni integer NOT NULL DEFAULT 0 CHECK (ni >= 0),
  poor integer NOT NULL DEFAULT 0 CHECK (poor >= 0),
  total double precision NOT NULL DEFAULT 0,
  hist jsonb NOT NULL DEFAULT '{}'::jsonb,
