-- One hour of raw samples grouped by dimensions and histogram bucket (the rollup job reads
-- this instead of paging through every row). Same bucket formula as the backend model.
CREATE OR REPLACE FUNCTION public.perf_hour_buckets(p_from timestamptz, p_to timestamptz)
RETURNS TABLE (
  metric text, route text, platform text, app_version text, device_class text, connection text, country text,
  bucket integer, cnt bigint, good bigint, ni bigint, poor bigint, total double precision
)
LANGUAGE sql STABLE SECURITY INVOKER SET search_path = public AS $$
  SELECT e.metric, e.route, e.platform, e.app_version, e.device_class, e.connection, e.country,
         CASE WHEN e.value <= 1 THEN 0 ELSE 1 + floor(ln(e.value) / ln(1.1))::integer END AS bucket,
         count(*) AS cnt,
         count(*) FILTER (WHERE e.rating = 0) AS good,
         count(*) FILTER (WHERE e.rating = 1) AS ni,
         count(*) FILTER (WHERE e.rating = 2) AS poor,
         sum(e.value)::double precision AS total
    FROM public.perf_events e
   WHERE e.at >= p_from AND e.at < p_to
   GROUP BY 1, 2, 3, 4, 5, 6, 7, 8
$$;

REVOKE ALL ON FUNCTION public.perf_hour_buckets(timestamptz, timestamptz) FROM PUBLIC, anon, authenticated;

CREATE TABLE IF NOT EXISTS public.perf_views (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_id uuid REFERENCES public.users (id) ON DELETE CASCADE,
  owner_username text,
  name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 60),
  query jsonb NOT NULL DEFAULT '{}'::jsonb,
  shared boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS perf_views_created_idx ON public.perf_views (created_at DESC);

CREATE TABLE IF NOT EXISTS public.perf_alert_rules (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL DEFAULT '' CHECK (char_length(name) <= 80),
  enabled boolean NOT NULL DEFAULT true,
  metrics text[] NOT NULL DEFAULT '{inp,appstart}'::text[],
  platforms text[] NOT NULL DEFAULT '{ios,android,electron,tauri}'::text[],
  threshold_pct integer NOT NULL DEFAULT 15 CHECK (threshold_pct BETWEEN 1 AND 500),
  min_sessions integer NOT NULL DEFAULT 2000 CHECK (min_sessions BETWEEN 10 AND 10000000),
  channels text[] NOT NULL DEFAULT '{adminRoom,ownerPush,errorLog}'::text[],
  mute text NOT NULL DEFAULT 'release24h' CHECK (mute IN ('none', 'release24h', '7d')),
  created_by uuid REFERENCES public.users (id) ON DELETE SET NULL,
  updated_by uuid REFERENCES public.users (id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.perf_alerts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  alert_key text NOT NULL,
  rule_id uuid REFERENCES public.perf_alert_rules (id) ON DELETE SET NULL,
  metric text NOT NULL,
  platform text NOT NULL,
  app_version text NOT NULL,
  prev_version text NOT NULL DEFAULT '',
  prev_p75 real,
  cur_p75 real,
  delta_pct real,
  sessions integer NOT NULL DEFAULT 0,
  share_pct real,
  top_routes text[] NOT NULL DEFAULT '{}'::text[],
  first_seen timestamptz NOT NULL DEFAULT now(),
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'hidden', 'resolved')),
  hidden_by uuid REFERENCES public.users (id) ON DELETE SET NULL,
  error_log_id bigint,
  notified jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS perf_alerts_key_idx ON public.perf_alerts (alert_key);
CREATE INDEX IF NOT EXISTS perf_alerts_status_idx ON public.perf_alerts (status, created_at DESC);

CREATE TABLE IF NOT EXISTS public.lighthouse_runs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  run_id text NOT NULL DEFAULT '',
  run_url text NOT NULL DEFAULT '',
  repo text NOT NULL DEFAULT '' CHECK (repo = '' OR repo ~ '^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$'),
  event text NOT NULL DEFAULT '' CHECK (event IN ('', 'pull_request', 'push', 'workflow_dispatch')),
  pr_number integer,
  merged_pr integer,
  pr_title text NOT NULL DEFAULT '' CHECK (char_length(pr_title) <= 200),
  pr_author text NOT NULL DEFAULT '' CHECK (char_length(pr_author) <= 60),
  branch text NOT NULL DEFAULT '' CHECK (char_length(branch) <= 120),
  sha text NOT NULL CHECK (sha ~ '^[0-9a-f]{7,40}$'),
  base_sha text NOT NULL DEFAULT '',
  page text NOT NULL CHECK (char_length(page) <= 120),
  form_factor text NOT NULL CHECK (form_factor IN ('mobile', 'desktop')),
  perf smallint CHECK (perf BETWEEN 0 AND 100),
  a11y smallint CHECK (a11y BETWEEN 0 AND 100),
  best_practices smallint CHECK (best_practices BETWEEN 0 AND 100),
  seo smallint CHECK (seo BETWEEN 0 AND 100),
  lcp_ms real,
  cls real,
  tbt_ms real,
  bytes bigint,
  bundle_gzip bigint,
  budgets_failed integer NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX IF NOT EXISTS lighthouse_runs_once_idx ON public.lighthouse_runs (run_id, sha, page, form_factor);
CREATE INDEX IF NOT EXISTS lighthouse_runs_created_idx ON public.lighthouse_runs (created_at DESC);
CREATE INDEX IF NOT EXISTS lighthouse_runs_pr_idx ON public.lighthouse_runs (pr_number, created_at DESC) WHERE pr_number IS NOT NULL;

