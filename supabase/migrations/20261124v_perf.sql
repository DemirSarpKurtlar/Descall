--
-- Real-user measurements (web-vitals attribution build + app timings) from every client
-- (web, iOS, Android, Electron, Tauri), plus the Lighthouse CI results of each workflow run.
--
-- perf_events: raw samples, one row per metric per page load. Sampled on the client
--   (one decision per page load) and sent in batches with navigator.sendBeacon to
--   POST /api/perf/beacon (rate limited, validated). No personal data beyond user_id
--   (from the session token, never from the payload) and the country from the edge
--   headers. Short retention: the backend deletes rows older than 14 days.
--   metric: lcp | inp | cls | fcp | ttfb | msglist | voicejoin | appstart | sess
--   (sess = one row per sampled page load, value 1; cls is stored x1000).
--   rating: 0 good, 1 needs improvement, 2 poor (web.dev thresholds, computed on insert).
-- perf_rollup_hourly / perf_rollup_daily: counts per dimension set with a sparse
--   log-scale histogram (hist: {"<bucket>": count}, bucket = 1 + floor(ln(v) / ln(1.1)),
--   0 for v <= 1), so any filter / time range merges exactly and p75 is read from the
--   merged histogram (about 5 % resolution). Written by the backend job every 5 minutes
--   (leader node only); hourly rows are kept 35 days, daily rows 400 days.
-- perf_views: saved query-bar views, shared with every admin who has the section.
-- perf_alert_rules: "Uyarı kuralı" dialog (threshold, minimum sessions, channels, mute).
-- perf_alerts: release regressions found by the job (banner, menu badge, notifications).
-- lighthouse_runs: one row per page and form factor of each Lighthouse CI run, written
--   by .github/workflows/lighthouse.yml with the service role (same as turnstile_config).
--
-- Only the backend (and the workflow) read and write them with the service role: RLS on,
-- no policies, no anon / authenticated grants. Additive, safe to re-run. Until it is
-- applied the beacon answers 204 and drops the batch, and the panel shows "not set up".

CREATE TABLE IF NOT EXISTS public.perf_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at timestamptz NOT NULL DEFAULT now(),
  session_id text NOT NULL CHECK (session_id ~ '^[A-Za-z0-9_-]{8,32}$'),
  user_id uuid,
  metric text NOT NULL CHECK (metric IN ('lcp', 'inp', 'cls', 'fcp', 'ttfb', 'msglist', 'voicejoin', 'appstart', 'sess')),
  value real NOT NULL CHECK (value >= 0 AND value <= 600000),
  rating smallint NOT NULL DEFAULT 0 CHECK (rating BETWEEN 0 AND 2),
  route text NOT NULL DEFAULT '' CHECK (char_length(route) <= 80),
  platform text NOT NULL CHECK (platform IN ('web', 'ios', 'android', 'electron', 'tauri')),
  app_version text NOT NULL DEFAULT '' CHECK (char_length(app_version) <= 24),
  device_class text NOT NULL DEFAULT '' CHECK (device_class IN ('', 'low', 'mid', 'high')),
  connection text NOT NULL DEFAULT '' CHECK (connection IN ('', 'wifi', 'ethernet', '4g', '3g', '2g', 'offline')),
  country text NOT NULL DEFAULT '' CHECK (country = '' OR country ~ '^[A-Z]{2}$'),
  browser text NOT NULL DEFAULT '' CHECK (char_length(browser) <= 24),
  nav_type text NOT NULL DEFAULT '' CHECK (char_length(nav_type) <= 16),
  sample_rate real NOT NULL DEFAULT 1 CHECK (sample_rate > 0 AND sample_rate <= 1),
  attribution jsonb
);

CREATE INDEX IF NOT EXISTS perf_events_at_idx ON public.perf_events (at DESC);
CREATE INDEX IF NOT EXISTS perf_events_user_idx ON public.perf_events (user_id, at DESC) WHERE user_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS perf_events_route_metric_idx ON public.perf_events (route, metric, at DESC);
CREATE INDEX IF NOT EXISTS perf_events_session_idx ON public.perf_events (session_id);

