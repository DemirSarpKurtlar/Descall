-- Hibrit sunucu (Render + the owner's PC), Yönetici Paneli › Sunucu Ağı (owner only, Nov 2026).
--
-- node_keys: the keys a secondary node (the owner's PC, "Descall Node") uses on
--   POST /api/node/register and /api/node/drain-done. The secret ("dsk_node_" + 43
--   base64url chars) is never stored: secret_hash is its SHA-256 hex; prefix / last4 are for
--   the list ("dsk_node_Ab3x…9QeK"). At most 5 are active (checked by the backend). A
--   revoke is final (the PC needs a new key).
-- node_settings: id 'pc' = the PC config (durable copy of the Key Value hash dc:cfg:pc:
--   RAM / CPU share, load rule, game mode, weekly schedule, alert switches), id 'ledger' =
--   this month's PC GB-hours for the saved-cost line. The Key Value store may restart, so
--   the backend puts the newer copy back.
-- node_events: durable copy of the events table (owner actions, drills, alerts; the live
--   ring stays in the Key Value list dc:events). The backend reads the newest 50.
--
-- Only the backend reads and writes them with the service role: RLS on, no policies, no
-- anon / authenticated grants. Additive, safe to re-run. Until it is applied the Sunucu Ağı
-- tab still works from the cluster state; node keys show "not set up" and dsk_node_
-- bearers are refused.

CREATE TABLE IF NOT EXISTS public.node_keys (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 40),
  secret_hash text NOT NULL CHECK (secret_hash ~ '^[0-9a-f]{64}$'),
  prefix text NOT NULL,
  last4 text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid REFERENCES public.users (id) ON DELETE SET NULL,
  last_used_at timestamptz,
  last_used_node text,
  last_used_ip text,
  revoked_at timestamptz,
  revoked_by uuid REFERENCES public.users (id) ON DELETE SET NULL,
  revoke_reason text CHECK (revoke_reason IS NULL OR char_length(revoke_reason) BETWEEN 3 AND 300)
);

CREATE UNIQUE INDEX IF NOT EXISTS node_keys_secret_hash_key ON public.node_keys (secret_hash);
CREATE INDEX IF NOT EXISTS node_keys_active_idx ON public.node_keys (created_at DESC) WHERE revoked_at IS NULL;

CREATE TABLE IF NOT EXISTS public.node_settings (
  id text PRIMARY KEY CHECK (id IN ('pc', 'ledger')),
  value jsonb NOT NULL DEFAULT '{}'::jsonb,
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by uuid REFERENCES public.users (id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS public.node_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at timestamptz NOT NULL DEFAULT now(),
  kind text NOT NULL CHECK (char_length(kind) BETWEEN 1 AND 60),
  node_id text,
  detail jsonb,
  actor_id uuid REFERENCES public.users (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS node_events_at_idx ON public.node_events (at DESC);

ALTER TABLE public.node_keys ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.node_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.node_events ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.node_keys FROM anon, authenticated;
REVOKE ALL ON TABLE public.node_settings FROM anon, authenticated;
REVOKE ALL ON TABLE public.node_events FROM anon, authenticated;

GRANT ALL ON TABLE public.node_keys TO service_role;
GRANT ALL ON TABLE public.node_settings TO service_role;
GRANT ALL ON TABLE public.node_events TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.node_events_id_seq TO service_role;
