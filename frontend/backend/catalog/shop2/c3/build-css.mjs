function stillBlock(targets) {
  const list = targets.join(",\n  ");
  const lite = targets.map((t) => (t.startsWith(":root:root:root ") ? t.replace(":root:root:root ", ":root:root:root.gd-lite ") : `html.gd-lite ${t}`)).join(",\n");
  return `@media (prefers-reduced-motion: reduce) {
  ${list} {
    animation: none !important;
  }
}
${lite} {
  animation: none !important;
}`;
}

let extraSections = [];
export function addSection(css) { extraSections.push(css); }

const css = () => `${HEADER}\n\n${[...sections, ...extraSections, stillBlock(STILL_TARGETS)].join("\n\n")}\n`;

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const next = css();
  if (process.argv.includes("--check")) {
    const cur = readFileSync(outPath, "utf8");
    if (cur !== next) {
      console.error("shop2-c3.css is stale: run node backend/catalog/shop2/c3/build-css.mjs");
      process.exit(1);
    }
    console.log("shop2-c3.css up to date");
  } else {
    writeFileSync(outPath, next);
    console.log("wrote", outPath, `${(next.length / 1024).toFixed(1)} KB`);
  }
}
