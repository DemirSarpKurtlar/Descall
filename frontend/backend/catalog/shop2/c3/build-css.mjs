#!/usr/bin/env node
/**
 * Builds frontend/src/styles/shop2-c3.css from the Market 2.0 C3 render specs
 * (avatar effects, profile auras, presence flares, reaction bursts, call
 * overlays, themes). New effect keys only (all start with "s2-"); old
 * renderers are untouched.
 *
 *   node backend/catalog/shop2/c3/build-css.mjs          write the file
 *   node backend/catalog/shop2/c3/build-css.mjs --check  fail when stale
 */
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const outPath = join(here, "..", "..", "..", "..", "src", "styles", "shop2-c3.css");

const { MASK, MASK_CSS, TUBE_CSS, GLOSS_CSS } = require("./fx.js");
const sections = [];

const HEADER = `/* GENERATED by backend/catalog/shop2/c3/build-css.mjs from the C3 specs in
   backend/catalog/shop2/c3/, do not edit by hand.
   Market 2.0 motion catalog: avatar effects (incl. set profile effects),
   profile auras, presence flares, reaction bursts, call overlays, themes.
   Only new "s2-" keys. Motion is transform / opacity only; reduced motion,
   html.gd-lite and the idle / backgrounded app (app-backgrounded.css) get a
   still frame. */`;

/* ── Shared keyframes ─────────────────────────────────────────────── */
sections.push(`@keyframes s2fx-spin { to { transform: rotate(1turn); } }
@keyframes s2fx-sway { from { transform: rotate(-38deg); } to { transform: rotate(38deg); } }
@keyframes s2fx-breathe { 0%, 100% { opacity: 0.42; } 50% { opacity: 1; } }
@keyframes s2fx-twinkle { 0%, 100% { opacity: 1; } 50% { opacity: 0.22; } }
@keyframes s2fx-flicker { 0%, 100% { opacity: 1; } 7% { opacity: 0.45; } 9% { opacity: 1; } 41% { opacity: 0.88; } 43% { opacity: 0.3; } 45% { opacity: 1; } 72% { opacity: 0.92; } }
@keyframes s2fx-beat { 0% { opacity: 0.25; } 9% { opacity: 1; } 18% { opacity: 0.4; } 27% { opacity: 1; } 46%, 100% { opacity: 0.25; } }
@keyframes s2fx-flash { 0%, 86%, 100% { opacity: 0; } 88% { opacity: 1; } 91% { opacity: 0.15; } 94% { opacity: 0.95; } 97% { opacity: 0.2; } }`);

/* ── Avatar effects ──────────────────────────────────────────────── */
const { AVATAR } = require("./avatar.js");

function layerDecls(l) {
  const out = [];
  if (l.bg) out.push(`background: ${l.bg};`);
  if (l.mask && l.mask !== "none") {
    const m = MASK[l.mask];
    if (!m) throw new Error(`unknown mask ${l.mask}`);
    out.push(`-webkit-mask: ${m};`, `mask: ${m};`);
  }
  if (l.op != null) out.push(`opacity: ${l.op};`);
  if (l.anim) out.push(`animation: ${l.anim};`);
  return out;
}

const fxSel = (slug) => `.cosmetic-avatar-effect.effect-s2-${slug}`;
const avatarRules = [];
const glossSoftCss = GLOSS_CSS.replace(/0\.85/, "0.6").replace(/0\.28\)/, "0.18)");
const tubeLightCss = TUBE_CSS.replace(/0\.5\)/, "0.32)").replace(/0\.42\)/, "0.28)");
avatarRules.push(`/* Avatar effects: the box comes from avatarEffectGeometry (inset -(gap + w)).
   Base = solid band + soft outer glow; ::before / ::after = masked band layers.
   Shared geometry lives in custom properties (inherited by the pseudos). */
.cosmetic-avatar-effect[class*="effect-s2-"] {
  --s2r: calc(50% - var(--fx-w) / 2);
${Object.entries(MASK_CSS).map(([k, v]) => `  --s2m-${k}: ${v};`).join("\n")}
  --s2-tube: ${TUBE_CSS};
  --s2-tube-light: ${tubeLightCss};
  --s2-gloss: ${GLOSS_CSS};
  --s2-gloss-soft: ${glossSoftCss};
}
.cosmetic-avatar-effect[class*="effect-s2-"]::before,
.cosmetic-avatar-effect[class*="effect-s2-"]::after {
  content: "";
  position: absolute;
  inset: 0;
  border-radius: 50%;
  pointer-events: none;
  transform-origin: 50% 50%;
  backface-visibility: hidden;
}`);
for (const fx of AVATAR) {
  const sel = fxSel(fx.slug);
  avatarRules.push(`${sel} {
  box-shadow: inset 0 0 0 var(--fx-w) ${fx.base.solid}, 0 0 calc(var(--fx-w) * 1.6) ${fx.base.glow};
}`);
  for (const pseudo of ["before", "after"]) {
    if (!fx[pseudo]) continue;
    avatarRules.push(`${sel}::${pseudo} {\n  ${layerDecls(fx[pseudo]).join("\n  ")}\n}`);
  }
}
sections.push(avatarRules.join("\n"));

/* ── Profile auras ───────────────────────────────────────────────── */
const { AURA } = require("./aura.js");
const auraRules = [];
auraRules.push(`/* Profile auras (profile card, hover card, shop previews). The glass card
   pins its own box-shadow with !important, so the aura does too (:root lifts
   it over html.glass-desktop .user-profile-card). ::before = light rim,
   ::after = one motion layer; neither moves past the bottom edge. */
@keyframes s2au-sheen { 0% { transform: translateX(-130%); } 42%, 100% { transform: translateX(320%); } }
@keyframes s2au-drift { to { transform: translateX(-50%); } }
@keyframes s2au-glow { 0%, 100% { opacity: 0.55; transform: scale(0.94); } 50% { opacity: 1; transform: scale(1); } }
.cosmetic-profile-aura[class*="aura-s2-"]::before {
  content: "";
  position: absolute;
  inset: 0;
  padding: 1.5px;
  border-radius: inherit;
  pointer-events: none;
  z-index: 6;
  -webkit-mask: linear-gradient(#000 0 0) content-box, linear-gradient(#000 0 0);
  -webkit-mask-composite: xor;
  mask: linear-gradient(#000 0 0) content-box exclude, linear-gradient(#000 0 0);
}
.cosmetic-profile-aura[class*="aura-s2-"]::after {
  content: "";
  position: absolute;
  inset: 0;
  border-radius: inherit;
  pointer-events: none;
  z-index: 5;
}`);
for (const a of AURA) {
  const sel = `.cosmetic-profile-aura.aura-s2-${a.slug}`;
  auraRules.push(`:root ${sel} {\n  box-shadow: ${[...a.bloom, ...a.inner].join(", ")} !important;\n}`);
  auraRules.push(`.shop-profile-stage .shop-live-profile${sel} {\n  box-shadow: ${a.inner.join(", ")} !important;\n}`);
  const r = [];
  if (a.rim.shadow) r.push(`padding: 0;`, `-webkit-mask: none;`, `mask: none;`, `box-shadow: ${a.rim.shadow};`);
  else r.push(`background: ${a.rim.bg};`);
  if (a.rimW) r.push(`padding: ${a.rimW}px;`);
  if (a.rimAnim) r.push(`animation: ${a.rimAnim};`);
  auraRules.push(`${sel}::before {\n  ${r.join("\n  ")}\n}`);
  if (a.fx) {
    const f = [`background: ${a.fx.bg};`];
    if (a.fx.kind === "sheen") f.push("inset: 0 auto 0 0;", "width: 55%;", "border-radius: 0;", "transform: translateX(-130%);");
    if (a.fx.kind === "drift") f.push("inset: 0 auto 0 0;", "width: 200%;", "border-radius: 0;");
    if (a.fx.origin) f.push(`transform-origin: ${a.fx.origin};`);
    if (a.fx.mask) f.push(`-webkit-mask: ${a.fx.mask};`, `mask: ${a.fx.mask};`);
    if (a.fx.op != null) f.push(`opacity: ${a.fx.op};`);
    else if (/s2fx-flash/.test(a.fx.anim || "")) f.push("opacity: 0.3;");
    if (a.fx.anim) f.push(`animation: ${a.fx.anim};`);
    auraRules.push(`${sel}::after {\n  ${f.join("\n  ")}\n}`);
  }
}
sections.push(auraRules.join("\n"));

/* ── Still frames ─────────────────────────────────────────────────── */
const STILL_TARGETS = [
  '.cosmetic-avatar-effect[class*="effect-s2-"]',
  '.cosmetic-avatar-effect[class*="effect-s2-"]::before',
  '.cosmetic-avatar-effect[class*="effect-s2-"]::after',
  '.cosmetic-profile-aura[class*="aura-s2-"]::before',
  '.cosmetic-profile-aura[class*="aura-s2-"]::after',
];

function stillBlock(targets) {
  const list = targets.join(",\n  ");
  const lite = targets.map((t) => `html.gd-lite ${t}`).join(",\n");
  return `@media (prefers-reduced-motion: reduce) {
  ${list} {
    animation: none !important;
  }
}
${lite} {
  animation: none !important;
}`;
}

let extraSections = [];
export function addSection(css) { extraSections.push(css); }

const css = () => `${HEADER}\n\n${[...sections, ...extraSections, stillBlock(STILL_TARGETS)].join("\n\n")}\n`;

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const next = css();
  if (process.argv.includes("--check")) {
    const cur = readFileSync(outPath, "utf8");
    if (cur !== next) {
      console.error("shop2-c3.css is stale: run node backend/catalog/shop2/c3/build-css.mjs");
      process.exit(1);
    }
    console.log("shop2-c3.css up to date");
  } else {
    writeFileSync(outPath, next);
    console.log("wrote", outPath, `${(next.length / 1024).toFixed(1)} KB`);
  }
}
