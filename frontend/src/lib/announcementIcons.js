/** Icon key of a row (new `icon`, else the legacy emoji, else the megaphone). */
export function announcementIconKey(row) {
  const key = String(row?.icon || "").trim();
  if (ANN_ICON_KEYS.includes(key)) return key;
  const raw = String(row?.emoji || "").trim();
  return LEGACY_EMOJI_ICON[raw] || LEGACY_EMOJI_ICON[raw.replace(/️/g, "")] || "megaphone";
}

