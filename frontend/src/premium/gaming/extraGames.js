let merged = null;

/** Extra entries (lower-case exe -> entry) for members with game_status, else {}. */
export function premiumProcessEntries(base = {}) {
  if (!hasPremiumFeature("game_status")) return null;
  if (!merged) {
    merged = {};
    for (const [exe, entry] of Object.entries(EXTRA_GAMES)) {
      const k = exe.toLowerCase();
      if (!base[k]) merged[k] = entry;
    }
  }
  return merged;
}
