import assert from "node:assert/strict";
import * as m from "./statsModel.js";
import { ADMINX_TR } from "../../../i18n/locales/adminx.tr.js";
import { ADMINX_EN } from "../../../i18n/locales/adminx.en.js";
import { formatMessage } from "../../../i18n/message.js";

const tFor = (cat, tag) => (key, vars) => {
  const raw = key.replace(/^adminx\./, "").split(".").reduce((o, p) => o?.[p], cat);
  assert.equal(typeof raw, "string", `missing ${key}`);
  return formatMessage(raw, vars, tag);
};
const tr = tFor(ADMINX_TR, "tr-TR");
const en = tFor(ADMINX_EN, "en-GB");

assert.equal(m.rangeLabel("2026-09-27", "2026-10-26", "tr"), "27 Eyl – 26 Eki 2026");
assert.equal(m.rangeLabel("2025-12-01", "2026-01-05", "tr"), "1 Ara 2025 – 5 Oca 2026");
assert.match(m.rangeLabel("2026-09-27", "2026-10-26", "en"), /^27 Sep.? – 26 Oct 2026$/);
assert.equal(m.rangeCaption("2026-09-27", "2026-10-26", "2026-10-26", tr, "tr"), "son 30 gün");
assert.equal(m.rangeCaption("2026-09-27", "2026-10-26", "2026-10-26", en, "en"), "last 30 days");
assert.equal(m.rangeCaption("2026-09-27", "2026-10-20", "2026-10-26", tr, "tr"), "27 Eyl – 20 Eki 2026");
assert.equal(m.sinceText("2026-04-18", tr, "tr"), "18 Nis 2026'dan beri");
assert.equal(m.sinceText("2030-01-02", tr, "tr"), "2 Oca 2030'dan beri");
assert.equal(m.sinceText("2026-04-18", en, "en"), "since 18 Apr 2026");
assert.deepEqual(m.kpiDelta("today", { dir: "up", value: 2 }, tr, "tr"), { mark: "▲ 2", cls: "", rest: " dünden fazla" });
assert.equal(m.kpiDelta("week", { dir: "up", value: 14 }, tr, "tr").rest, " geçen haftaya göre");
assert.equal(m.kpiDelta("month", { dir: "up", value: null }, tr, "tr").rest, "önceki 30 günde kayıt yoktu");
assert.equal(m.kpiDelta("week", { dir: "down", value: 3 }, tr, "tr").mark, "▼ %3");
assert.equal(m.kpiDelta("week", { dir: "down", value: 3 }, en, "en").mark, "▼ 3%");
assert.deepEqual(m.tickIndexes(30), [0, 7, 14, 21, 29]);
assert.equal(m.niceMax(9), 10);
assert.equal(m.niceMax(11), 20);
assert.equal(m.niceMax(41), 50);
assert.equal(m.niceMax(120), 200);
assert.equal(m.dec1(5.2857, "tr"), "5,3");
assert.equal(m.dec1(5.2857, "en"), "5.3");
assert.equal(m.num(1234, "tr"), "1.234");
assert.equal(m.axisLabel({ key: "2026-01-01" }, "month", "tr"), "Oca 2026");
assert.equal(m.axisLabel({ key: "2026-10-01" }, "month", "tr"), "Eki");
assert.equal(m.tipLabel({ key: "2026-10-19" }, "week", tr, "tr"), "19 Eki 2026 haftası");
assert.equal(m.tipLabel({ key: "2026-10-01" }, "month", tr, "tr"), "Ekim 2026");
assert.equal(tr("adminx.sst.tipCount", { count: 1234 }), "1.234 kayıt");
assert.equal(en("adminx.sst.tipCount", { count: 1 }), "1 sign-up");
assert.equal(m.peakIndex([{ count: 2 }, { count: 9 }, { count: 9 }]), 1);
assert.equal(m.flag("TR"), "🇹🇷");
assert.equal(m.countryRow({ code: "DE", count: 7 }, 1, tr, "tr").label, "🇩🇪 Almanya");
assert.equal(m.countryRow({ code: "TR", count: 7 }, 0, tr, "tr").label, "🇹🇷 Türkiye");
assert.equal(m.countryRow({ code: "DE", count: 7 }, 1, en, "en").label, "🇩🇪 Germany");
assert.equal(m.countryRow({ code: "unknown", count: 7 }, 3, tr, "tr").muted, true);
assert.equal(m.countryRow({ code: "unknown", count: 7 }, 3, tr, "tr").label, "Bilinmiyor");
assert.equal(m.sourceLabel({ key: "direct", label: "Doğrudan" }, en), "Direct");
assert.equal(m.sourceLabel({ key: "discord", label: "Discord" }, en), "Discord");
assert.deepEqual(m.AUTH_SEGMENTS.map((s) => m.authLabel(s, tr)), ["E-posta", "Google", "Diğer", "Bilinmiyor"]);
for (const [, key] of [...m.GRANULARITIES, ...m.PRESETS]) { tr(key); en(key); }
console.log("statsModel.selftest ok");
